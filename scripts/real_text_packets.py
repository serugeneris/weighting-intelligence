"""Pilot AL review packets: the author's item check (Stage 1) and the blind human baseline (Stage 2).

  python3 scripts/real_text_packets.py review            -> docs/reviews/real-text-skill/item-review.md
  python3 scripts/real_text_packets.py baseline          -> docs/reviews/real-text-skill/baseline/{packet.json,
                                                            key.json,answer.html}
  python3 scripts/real_text_packets.py score ANSWERS.json [ANSWERS2.json ...]   -> agreement with the keys per grader

`review` lists every item with the corrupted sentence marked, so the author can check that each original's conclusion
follows, each corruption breaks exactly that, each paraphrase keeps the meaning, and each real reply is unambiguous;
verdicts go into the review.status fields of the data files. `baseline` draws a fixed 20-item subset (10 per task: 5
original-vs-corrupted and 5 paraphrase-vs-corrupted; 5 objection->reply and 5 reply->objection, original wording) with a
fixed seed. packet.json and answer.html are what graders see; key.json must stay away from them. The gate is >= 85%
agreement with the keys per grader. Standard library only.
"""
import html
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from scripts import philbench_items as items_mod  # noqa: E402

OUT = ROOT / "docs/reviews/real-text-skill"
PACKET_ID = "al-human-baseline-v1"
SEED = 20261120
GATE = 0.85
SENTENCE = re.compile(r"(?<=[.?!])\s+(?=[A-Z])")


def load(name):
    return json.loads((ROOT / "data" / name).read_text())


def review():
    corr, objr = load("pilot-real-corruption.json"), load("pilot-real-objreply.json")
    lines = ["# Pilot AL: item review", "",
             "Generated by `python3 scripts/real_text_packets.py review` from `data/pilot-real-corruption.json` and "
             "`data/pilot-real-objreply.json`. For each item, check and record a verdict in the item's `review` field "
             "(`{\"status\": \"ok\"}`, or `\"fix\"` / `\"drop\"` with a `note`).", "",
             "**Task 1 (corrupt).** The original's conclusion follows; the corruption (in bold) breaks exactly that and "
             "nothing else; the paraphrase keeps the meaning.", "",
             "**Task 2 (objreply).** The reply answers this objection and no other in the exchange; excerpts are fair "
             "to the source; paraphrases keep the meaning.", ""]
    lines += ["## Task 1: corrupted arguments", ""]
    for n, it in enumerate(corr["items"], 1):
        sents = SENTENCE.split(it["corrupted"])
        k = it["corrupted_sentence"] - 1
        sents[k] = f"**{sents[k]}**"
        lines += [f"### 1.{n} `{it['id']}` ({it['corruption_type']}, sentence {k + 1})", "",
                  f"{it['edition']}. {it['location']}.", ""]
        if it.get("adaptation"):
            lines += [f"*Adaptation:* {it['adaptation']}", ""]
        lines += [f"- **Original.** {it['original']}", f"- **Corrupted.** {' '.join(sents)}",
                  f"- **Paraphrase.** {it['paraphrase']}", f"- Verdict: `{it['review']['status']}`", ""]
    lines += ["## Task 2: objection-reply pairs", ""]
    for ex in objr["exchanges"]:
        lines += [f"### {ex['edition']}", ""]
        for p in ex["pairs"]:
            lines += [f"#### `{p['id']}`{' (reply echoes the objection)' if p['echo'] else ''}", "",
                      f"{p['location']}.{(' *Adaptation:* ' + p['adaptation']) if p.get('adaptation') else ''}", "",
                      f"- **Objection.** {p['objection']}", f"- **Reply.** {p['reply']}",
                      f"- *Objection, paraphrased.* {p['objection_paraphrase']}",
                      f"- *Reply, paraphrased.* {p['reply_paraphrase']}", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "item-review.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT / 'item-review.md'}")


def baseline():
    rng = random.Random(SEED)
    corr = [it for it in items_mod.corrupt() if it["expected"]]
    objr = [it for it in items_mod.objreply() if it["form"] == "original"]
    args = sorted({it["item"] for it in corr})
    rng.shuffle(args)
    chosen = []
    for i, arg in enumerate(args[:10]):
        pair = "orig-corr" if i < 5 else "para-corr"
        chosen.append(rng.choice([it for it in corr if it["item"] == arg and it["pair"] == pair]))
    pairs = sorted({it["item"] for it in objr})
    rng.shuffle(pairs)
    for i, pid in enumerate(pairs[:10]):
        direction = "obj->reply" if i < 5 else "reply->obj"
        chosen += [it for it in objr if it["item"] == pid and it["direction"] == direction]
    rng.shuffle(chosen)
    packet = {"packet": PACKET_ID, "items": [{"id": f"q{n:02d}", "prompt": it["user"], "labels": it["labels"]}
                                             for n, it in enumerate(chosen, 1)]}
    key = {"packet": PACKET_ID, "items": {f"q{n:02d}": {"task": it["task"], "item": it["item"],
                                                        "variant": it["variant"], "expected": it["expected"]}
                                          for n, it in enumerate(chosen, 1)}}
    out = OUT / "baseline"
    out.mkdir(parents=True, exist_ok=True)
    (out / "packet.json").write_text(json.dumps(packet, indent=2, ensure_ascii=False) + "\n")
    (out / "key.json").write_text(json.dumps(key, indent=2) + "\n")
    (out / "answer.html").write_text(answer_page(packet))
    print(f"wrote {out}/packet.json, key.json, answer.html ({len(chosen)} items)")


