def score(paths):
    key = json.loads((OUT / "baseline/key.json").read_text())
    disputed = {}
    for path in paths:
        ans = json.loads(Path(path).read_text())
        assert ans["packet"] == key["packet"], f"{path}: answers are for another packet"
        per_task = {}
        for qid, k in key["items"].items():
            ok = ans["answers"].get(qid) == k["expected"]
            per_task.setdefault(k["task"], []).append(ok)
            if not ok:
                disputed.setdefault(qid, {**k, "graders": []})["graders"].append(ans["grader"])
        total = [x for v in per_task.values() for x in v]
        rate = sum(total) / len(total)
        print(f"{ans['grader']}: {sum(total)}/{len(total)} = {rate:.0%} "
              + " ".join(f"{t} {sum(v)}/{len(v)}" for t, v in per_task.items())
              + ("" if rate >= GATE else f"  BELOW THE {GATE:.0%} GATE"))
    for qid, d in sorted(disputed.items()):
        print(f"  disputed {qid}: {d['task']} {d['item']} [{d['variant']}] key {d['expected']}, missed by "
              f"{', '.join(d['graders'])}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "review":
        review()
    elif cmd == "baseline":
        baseline()
    elif cmd == "score" and len(sys.argv) > 2:
        score(sys.argv[2:])
    else:
        print(__doc__)
